"""Chat history."""

from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, Integer, String, Text, UniqueConstraint
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.db import Base


class Chat(Base):
    __tablename__ = "chats"

    id: Mapped[str] = mapped_column(String(64), primary_key=True)  # generated by the frontend
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    title: Mapped[str] = mapped_column(String)
    title_by: Mapped[str | None] = mapped_column(String(8))  # "user" | "ai" | None (default title)
    titled_at: Mapped[int | None] = mapped_column(Integer)  # user-turn count at the last auto-title
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), index=True)

    messages: Mapped[list["Message"]] = relationship(
        back_populates="chat", cascade="all, delete-orphan", order_by="Message.position"
    )


class Message(Base):
    __tablename__ = "messages"

    id: Mapped[int] = mapped_column(primary_key=True)
    chat_id: Mapped[str] = mapped_column(ForeignKey("chats.id", ondelete="CASCADE"), index=True)
    position: Mapped[int] = mapped_column(Integer)
    role: Mapped[str] = mapped_column(String(16))
    content: Mapped[str] = mapped_column(Text)
    ui: Mapped[str | None] = mapped_column(String(16))  # "error" | "stopped" for non-answer bubbles
    sources: Mapped[list | None] = mapped_column(JSONB)  # chunks cited by an assistant answer
    feedback: Mapped[str | None] = mapped_column(String(4))  # "up" | "down": the user's rating (models/feedback.py)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))

    __table_args__ = (UniqueConstraint("chat_id", "position", name="uq_messages_chat_position"),)

    chat: Mapped[Chat] = relationship(back_populates="messages")
