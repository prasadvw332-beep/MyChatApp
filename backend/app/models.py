from datetime import datetime

from sqlalchemy import BigInteger, DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db import Base


class EvalRun(Base):
    """One RAGAS evaluation run; `rows` holds the per-question answers, contexts and scores."""

    __tablename__ = "eval_runs"

    id: Mapped[str] = mapped_column(String(15), primary_key=True)  # YYYYMMDD_HHMMSS
    created_at: Mapped[datetime]
    duration_s: Mapped[int] = mapped_column(Integer)
    chat_model: Mapped[str] = mapped_column(String)
    judge_model: Mapped[str] = mapped_column(String)
    metrics: Mapped[list] = mapped_column(JSONB)
    summary: Mapped[dict] = mapped_column(JSONB)
    scored: Mapped[dict] = mapped_column(JSONB)
    no_context: Mapped[int] = mapped_column(Integer)
    rows: Mapped[list] = mapped_column(JSONB)


class Chat(Base):
    __tablename__ = "chats"

    id: Mapped[str] = mapped_column(String(64), primary_key=True)  # generated by the frontend
    title: Mapped[str] = mapped_column(String)
    title_by: Mapped[str | None] = mapped_column(String(8))  # "user" | "ai" | None (default title)
    titled_at: Mapped[int | None] = mapped_column(Integer)  # user-turn count at the last auto-title
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), index=True)

    messages: Mapped[list["Message"]] = relationship(
        back_populates="chat", cascade="all, delete-orphan", order_by="Message.position"
    )


class Message(Base):
    __tablename__ = "messages"

    id: Mapped[int] = mapped_column(primary_key=True)
    chat_id: Mapped[str] = mapped_column(ForeignKey("chats.id", ondelete="CASCADE"), index=True)
    position: Mapped[int] = mapped_column(Integer)
    role: Mapped[str] = mapped_column(String(16))
    content: Mapped[str] = mapped_column(Text)
    ui: Mapped[str | None] = mapped_column(String(16))  # "error" | "stopped" for non-answer bubbles
    sources: Mapped[list | None] = mapped_column(JSONB)  # chunks cited by an assistant answer
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))

    chat: Mapped[Chat] = relationship(back_populates="messages")


class Document(Base):
    """An uploaded file. The original lives in MinIO, the chunks/vectors in Qdrant."""

    __tablename__ = "documents"

    doc_id: Mapped[str] = mapped_column(String(32), primary_key=True)
    filename: Mapped[str] = mapped_column(String)
    ext: Mapped[str] = mapped_column(String(8))
    size_bytes: Mapped[int] = mapped_column(BigInteger)
    sha256: Mapped[str | None] = mapped_column(String(64), index=True)
    chunks: Mapped[int] = mapped_column(Integer, default=0)
    minio_key: Mapped[str | None] = mapped_column(String)
    status: Mapped[str] = mapped_column(String(16), default="indexing")  # indexing | ready
    tags: Mapped[list] = mapped_column(JSONB, default=list)
    uploaded_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
